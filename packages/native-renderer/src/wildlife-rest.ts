const restSkeleton = new Skeleton([{ name: 'body', x: 0, y: 0 }]);
let art: readonly { color: Rgb; commands: Command[] }[] | undefined;
export function restingPig(): SceneNode {
  art ??= pig.map(({ color, loops }) => ({
    color,
    commands: new SkinnedPath(
      restSkeleton,
      loops.map((loop) => loop.map(([x, y, corner]) => [x, y, 'body', corner])),
    ).commands([identity]),
  }));
  const scene = new SceneNode();
  for (const { color, commands } of art) {
    const shape = new ShapeNode().fill(...color);
    shape.commands = commands;
    scene.add(shape);
  }
  return scene;
}
